#!/usr/bin/env python3
"""Build docs/quality_metrics.md from the files the other checks produce.

Inputs: coverage summary, static analysis baseline, RTM results, defect records (defects/issues),
fuzzing record, test scripts. No timestamps, so `--check` fails when the page is out of date.
"""
import argparse, collections, glob, json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
OUT = os.path.join(ROOT, "docs", "quality_metrics.md")


def load(rel):
    return json.load(open(os.path.join(ROOT, rel)))


def defects():
    out = []
    for p in sorted(glob.glob(os.path.join(ROOT, "defects", "issues", "*.md"))):
        meta = re.match(r"---\n(.*?)\n---", open(p).read(), re.S).group(1)
        title = re.search(r'^title: "(.*)"$', meta, re.M).group(1)
        labels = [l.strip().strip('"') for l in re.search(r"^labels: \[(.*)\]$", meta, re.M).group(1).split(",")]
        get = lambda prefix: next((l[len(prefix):] for l in labels if l.startswith(prefix)), "-")
        out.append(dict(id=title.split(":")[0], title=title.split(": ", 1)[1], kind="defect" if "defect" in labels else "test-infra",
                        sev=get("sev:"), found=get("found-by:"), state=get("state:") if "defect" in labels else "closed",
                        open=re.search(r"^state: (\w+)$", meta, re.M).group(1) == "open"))
    return out


def test_executables():
    names = []
    for script in ("sut/run_tests.sh",):
        for line in open(os.path.join(ROOT, script)):
            if line.lstrip().startswith("#"):
                continue
            names += re.findall(r"\brun ([a-z_0-9]+) ", line)
            if "wrap_pi" in line and "for fl in" in line:
                names += ["wrap_pi", "wrap_pi_float"]
            if "safety_reqs" in line and "gcc" in line:
                names.append("safety_reqs")
    return sorted(set(names))


def build():
    cov = load("verification/results/coverage_summary.json")
    base = load("verification/static/baseline.json")
    rtm = load("verification/traceability/results.json")
    fuzz = load("verification/results/fuzz_runs.json")
    D = defects()
    counts = base["counts"]
    misra = sum(n for k, n in counts.items() if "|misra" in k)
    other = sum(n for k, n in counts.items() if "|misra" not in k)
    rules = len({k.split("|")[1] for k in counts if "|misra" in k})
    reqs = rtm["requirements"]
    with_ut = sum(1 for r in reqs if r["unit_tests"])
    tests = test_executables()
    prod = [d for d in D if d["kind"] == "defect"]
    L = ["# Quality Metrics", "",
         "Generated by `verification/metrics/build_metrics.py` from the files CI checks. Do not edit by hand; CI fails when this page is out of date.", "",
         "## Summary", "", "| Area | Metric | Value | Source |", "|---|---|---|---|",
         f"| Unit tests | Test executables (host, ASan+UBSan) | {len(tests)} | `sut/run_tests.sh`, `sut/quality.sh` |",
         f"| Coverage | Line | {cov['line_percent']}% ({cov['line_covered']}/{cov['line_total']}) | `verification/results/coverage_summary.json` |",
         f"| Coverage | Branch | {cov['branch_percent']}% ({cov['branch_covered']}/{cov['branch_total']}) | same |",
         f"| Coverage | Function | {cov['function_percent']}% ({cov['function_covered']}/{cov['function_total']}) | same |",
         f"| Static analysis | MISRA C:2012 findings (baseline) | {misra} over {rules} rules | `verification/static/baseline.json` |",
         f"| Static analysis | Other findings (clang-tidy, cppcheck) | {other} | same |",
         f"| Static analysis | New findings allowed by CI | 0 | `sut/static_analysis.py` |",
         f"| Requirements | Acceptance criteria judged | {rtm['summary']['PASS']} pass, {rtm['summary']['FAIL']} fail, {rtm['summary']['NOT_JUDGED']} not judged | `verification/traceability/results.json` |",
         f"| Requirements | With a linked unit test | {with_ut}/{len(reqs)} | same |",
         f"| HILS/SILS | Recorded laps in the published data | {rtm['inputs']['rows']} ({rtm['inputs']['valid']} valid) | `verification/results/summary.csv` |",
         f"| Defects | Found (product) | {len(prod)}: {sum(1 for d in prod if d['open'])} open, {sum(1 for d in prod if d['state']=='verified-on-board')} verified on the board | `defects/issues/` |",
         f"| Defects | Test infrastructure | {sum(1 for d in D if d['kind']=='test-infra')} | same |",
         f"| Fuzzing | Longest run | {max(r['hours'] for r in fuzz['runs'])} h per build, {sum(r['executions'] or 0 for r in fuzz['runs'])/1e6:.1f} M executions in total, {sum(r['crashes'] for r in fuzz['runs'])} crash (DEF-6) | `verification/results/fuzz_runs.json` |",
         "", "## Defects by how they were found", "",
         "Different techniques found different defects, and no single technique found all of them. Whether one technique would also have found another's defect was not tested.", "",
         "| Found by | Defects | IDs |", "|---|---:|---|"]
    by = collections.defaultdict(list)
    for d in D:
        by[d["found"]].append(d["id"])
    for k, ids in sorted(by.items(), key=lambda x: (-len(x[1]), x[0])):
        L.append(f"| {k.replace('-', ' ')} | {len(ids)} | {', '.join(ids)} |")
    L += ["", "## Defect status", "", "| ID | Defect | Severity | Found by | State |", "|---|---|---|---|---|"]
    for d in D:
        st = {"verified-on-board": "verified on the board", "fixed-not-on-board": "fixed in code, **not yet on the board**",
              "open": "**open**", "closed": "closed"}[d["state"]]
        L.append(f"| {d['id']} | {d['title']} | {d['sev']} | {d['found'].replace('-', ' ')} | {st} |")
    L += ["", "Defect lifecycle: open → fixed in code with a regression test that fails on the old code → verified in HILS laps on the board → closed. "
          "DEF-5 to DEF-7 stay open until they have run on the board.", "",
          "## Requirements without a unit test", "",
          ", ".join(r["id"] for r in reqs if not r["unit_tests"]) + ".", ""] + ["- " + g for g in rtm["known_gaps"]] + ["",
          "## Not measured", "",
          "- Coverage is from the host build, not the S32K312.",
          "- Mutation testing was last run on 2026-11-05, before the QP and safety changes (see README).",
          "- No defect density per KLOC: one project and one developer give no meaningful baseline.",
          "- Measured solve times are not a WCET bound.", ""]
    return "\n".join(L)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    text = build()
    if a.check:
        cur = open(OUT).read() if os.path.exists(OUT) else ""
        if cur != text:
            sys.exit("docs/quality_metrics.md is out of date: run verification/metrics/build_metrics.py")
        print("quality metrics up to date")
    else:
        open(OUT, "w").write(text)
        print("wrote", OUT)
