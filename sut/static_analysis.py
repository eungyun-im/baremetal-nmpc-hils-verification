#!/usr/bin/env python3
"""Static analysis with cppcheck (MISRA C 2012 addon) and clang-tidy.

Findings are compared with verification/static/baseline.json by tool, rule,
file and message, without line numbers, so moving code does not count as new.
Exit 1 when a key appears more often than in the baseline.

  sut/static_analysis.py                    # run and compare
  sut/static_analysis.py --update-baseline  # accept the current findings
"""
import argparse, collections, json, os, re, shutil, subprocess, sys
import xml.etree.ElementTree as ET

SUT = os.path.dirname(os.path.abspath(__file__)); ROOT = os.path.dirname(SUT)
OUT = os.path.join(SUT, "build_static"); BASE = os.path.join(ROOT, "verification", "static", "baseline.json")
BEFORE_SAFETY_REQUIRED = 18   # measured with cppcheck 2.13 before the safety layer cleanup, 2026-11-07
SOURCES = sorted([os.path.join("core/src", f) for f in os.listdir(os.path.join(SUT, "core/src")) if f.endswith(".c")] +
                 ["integ/bmpc_safety.c", "third_party/kuuve_safety/safety_ctrl.c"])
INC = ["-Icore/include", "-Iinteg", "-Ithird_party/kuuve_safety"]
DEFS = ["-DBMPC_USE_FLOAT", "-DBS_PLAUS", "-D_POSIX_C_SOURCE=200809L"]
TIDY = "clang-analyzer-*,bugprone-*,cert-*,performance-*,portability-*,-bugprone-easily-swappable-parameters"


def tool_version(cmd):
    try:
        out = subprocess.run([cmd, "--version"], capture_output=True, text=True).stdout.strip().splitlines()
        return next((l.strip() for l in out if "version" in l.lower() or l.lower().startswith("cppcheck")), out[0] if out else None)
    except OSError:
        return None


def run_cppcheck(exe):
    xml = os.path.join(OUT, "cppcheck.xml")
    cmd = [exe, "--enable=warning,style,performance,portability", "--std=c99", "--addon=misra", "--inline-suppr",
           "--suppress=missingIncludeSystem", "--xml", "--output-file=" + xml] + INC + DEFS + SOURCES
    r = subprocess.run(cmd, cwd=SUT, capture_output=True, text=True)
    if not os.path.exists(xml):
        sys.exit("cppcheck produced no report: " + r.stderr[-500:])
    found = []
    for e in ET.parse(xml).getroot().iter("error"):
        loc = e.find("location")
        if loc is None:
            continue
        rule = e.get("id")
        if rule.startswith("misra"):
            rule = "misra-c2012-" + re.sub(r"^misra-c2012-", "", rule)
        found.append(dict(tool="cppcheck", rule=rule, severity=e.get("severity"), file=os.path.relpath(os.path.join(SUT, loc.get("file")), SUT),
                          line=int(loc.get("line", 0)), message=e.get("msg", "")))
    return found


def run_clang_tidy(exe):
    found = []
    pat = re.compile(r"^(.+?):(\d+):\d+: (warning|error): (.*) \[([^\]]+)\]$")
    for src in SOURCES:
        r = subprocess.run([exe, "-checks=-*," + TIDY, src, "--", "-std=c99"] + INC + DEFS, cwd=SUT, capture_output=True, text=True)
        for line in r.stdout.splitlines():
            m = pat.match(line)
            if m and "clang-diagnostic" not in m.group(5):
                found.append(dict(tool="clang-tidy", rule=m.group(5), severity=m.group(3), file=os.path.relpath(os.path.join(SUT, m.group(1)), SUT),
                                  line=int(m.group(2)), message=m.group(4)))
    uniq = {(f["file"], f["line"], f["rule"], f["message"]): f for f in found}   # headers repeat across sources
    return sorted(uniq.values(), key=lambda f: (f["file"], f["line"], f["rule"]))


def key(f):
    return "%s|%s|%s|%s" % (f["tool"], f["rule"], f["file"], re.sub(r"\d+", "N", f["message"]))


def report(found, versions, path):
    disp = json.load(open(os.path.join(ROOT, "verification", "static", "dispositions.json")))
    misra = [f for f in found if f["rule"].startswith("misra")]; other = [f for f in found if not f["rule"].startswith("misra")]
    rc = collections.Counter(f["rule"].replace("misra-c2012-", "") for f in misra)
    cat = collections.Counter()
    for r, n in rc.items():
        cat[disp["misra"].get(r, ["Unknown"])[0]] += n
    L = ["# Static Analysis", "", "Generated by `sut/static_analysis.py --report`. Tools: %s, %s." % (versions["cppcheck"], versions["clang_tidy"]), "",
         "Scope: %d files in `core/src`, `integ` and `third_party/kuuve_safety`, analyzed as the float build with the plausibility check on. `platform/` is not analyzed." % len(SOURCES), "",
         "> " + disp["note"], "",
         "**%d findings: %d MISRA C:2012 findings over %d rules (%s), and %d other findings.** CI fails when a new finding appears that is not in `verification/static/baseline.json`." % (
             len(found), len(misra), len(rc), ", ".join("%s %d" % (k, v) for k, v in sorted(cat.items())), len(other)), "",
         "## Real defect found and fixed", "", "MISRA rule 14.1 flags the floating-point loops in `bm_wrap_pi` (`core/include/bmpc/bmpc_math.h`). An earlier unit test review reproduced a hang there: for a very large angle, subtracting 2π no longer changes the value and the loop never ends. Normal CAN inputs cannot reach it. It is tracked as DEF-5. The fix reduces angles beyond ±64π with `fmod` first and keeps the old arithmetic otherwise; `test_wrap_pi.c` fails on the old code and checks bitwise equality on 571,429 inputs. The rule 14.1 finding remains, because the bounded loops are still floating-point loops. **The fix has not run on the board yet.**", "",
         "## Safety layer", "", "The safety layer (`integ/bmpc_safety.*`, `third_party/kuuve_safety/safety_ctrl.c`) was cleaned first because it handles faults. **Required-rule findings there went from %d to %d.** The changes are braces, parentheses, explicit comparisons, casts and split declarations, with no change in behavior; all unit tests pass unchanged. The remaining findings are kept as deviations:" % (BEFORE_SAFETY_REQUIRED, sum(1 for f in found if "safety" in f["file"] and f["rule"].startswith("misra") and disp["misra"].get(f["rule"][12:], [""])[0] == "Required")), "",
         "| Rule | Count | Reason |", "|---|---:|---|"] + ["| %s | %d | %s |" % (r, n, disp["safety_layer"].get(r, "Not reviewed.")) for r, n in collections.Counter(f["rule"].replace("misra-c2012-", "") for f in found if "safety" in f["file"]).most_common()] + ["",
         "## Other findings", "", "| Tool | Rule | Count | Disposition |", "|---|---|---:|---|"]
    for (t, r), n in sorted(collections.Counter((f["tool"], f["rule"]) for f in other).items(), key=lambda x: -x[1]):
        L.append("| %s | `%s` | %d | %s |" % (t, r, n, disp["other"].get(r, "Not reviewed.")))
    L += ["", "## MISRA C:2012 by rule", "", "| Rule | Category | Topic | Count | Disposition |", "|---|---|---|---:|---|"]
    for r, n in sorted(rc.items(), key=lambda x: -x[1]):
        c, t, d = disp["misra"].get(r, ["?", "?", "Not reviewed."])
        L.append("| %s | %s | %s | %d | %s |" % (r, c, t, n, d))
    L += ["", "## MISRA findings by file", "", "| File | Count |", "|---|---:|"] + ["| `%s` | %d |" % (f, n) for f, n in collections.Counter(x["file"] for x in misra).most_common()]
    L += ["", "## Limits", "", "- The cppcheck MISRA addon covers only part of MISRA C:2012 and was run without the rule texts.",
          "- Most findings were reviewed by rule, not one by one. Only the non-MISRA findings and rules 14.1, 20.7 and 2.2 were looked at in the code.",
          "- Only the safety layer and `bm_wrap_pi` were changed. The MPC core keeps its findings, so it stays close to the build tested in HILS.", "- The changed firmware has been built but has not run on the board.", ""]
    open(path, "w").write("\n".join(L))


def main():
    ap = argparse.ArgumentParser(); ap.add_argument("--update-baseline", action="store_true")
    ap.add_argument("--from", dest="src", help="use a findings.json, for example from CI, instead of running the tools")
    ap.add_argument("--report", action="store_true", help="write docs/static_analysis.md"); a = ap.parse_args()
    os.makedirs(OUT, exist_ok=True)
    if a.src:
        d = json.load(open(a.src)); found, versions = d["findings"], d["versions"]
    else:
        cpp, tidy = shutil.which(os.environ.get("CPPCHECK", "cppcheck")), shutil.which(os.environ.get("CLANG_TIDY", "clang-tidy"))
        if not cpp or not tidy:
            sys.exit("cppcheck and clang-tidy are both required")
        found = run_cppcheck(cpp) + run_clang_tidy(tidy)
        versions = dict(cppcheck=tool_version(cpp), clang_tidy=tool_version(tidy))
        json.dump(dict(versions=versions, sources=SOURCES, findings=found), open(os.path.join(OUT, "findings.json"), "w"), indent=1)
    counts = collections.Counter(key(f) for f in found)
    if a.report:
        report(found, versions, os.path.join(ROOT, "docs", "static_analysis.md"))
    by_rule = collections.Counter((f["tool"], f["rule"]) for f in found)
    print("%d findings, %s" % (len(found), versions))
    for (t, r), n in by_rule.most_common(12):
        print("  %4d  %-10s %s" % (n, t, r))
    if a.update_baseline:
        json.dump(dict(versions=versions, counts=dict(sorted(counts.items()))), open(BASE, "w"), indent=1); open(BASE, "a").write("\n")
        print("baseline updated"); return
    if not os.path.exists(BASE):
        print("no baseline yet, nothing to compare"); return
    base = json.load(open(BASE))
    if base["versions"] != versions:
        print("warning: tool versions differ from the baseline %s" % base["versions"])
    new = {k: n - base["counts"].get(k, 0) for k, n in counts.items() if n > base["counts"].get(k, 0)}
    fixed = sum(max(0, n - counts.get(k, 0)) for k, n in base["counts"].items())
    print("new: %d, fixed since baseline: %d" % (sum(new.values()), fixed))
    for k, n in sorted(new.items()):
        print("  NEW x%d  %s" % (n, k))
    sys.exit(1 if new else 0)


if __name__ == "__main__":
    main()
